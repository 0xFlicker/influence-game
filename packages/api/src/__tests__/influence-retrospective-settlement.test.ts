import { expect, test } from "bun:test";
import { eq } from "drizzle-orm";
import { DEFAULT_CONFIG, GameRunner, replayCanonicalEvents } from "@influence/engine";
import { schema } from "../db/index.js";
import { ApiTestMockAgent } from "../services/game-lifecycle.js";
import { createDurableGameRunnerStore } from "../services/durable-game-runner-store.js";
import { settleDurableTerminalGame } from "../services/durable-game-terminal.js";
import { settleCapturedGameCompletion } from "../services/game-completion-settlement.js";
import { adoptInProgressDurableGamesOnStartup } from "../services/startup-durable-games.js";
import { initialGameTranscriptStateValues } from "../services/transcript-capture.js";
import { setupTestDB } from "./test-utils.js";
import { insertGame, insertOwner } from "./durable-run-test-utils.js";

test("outcome cannot settle; a restart after the final epilogue seals and publishes once", async () => {
  const db = await setupTestDB(), gameId = await insertGame(db, { status: "in_progress" });
  await db.update(schema.games).set({ transcriptCaptureVersion: 1, formalSpeechCaptureVersion: 1 }).where(eq(schema.games.id, gameId));
  await db.insert(schema.gameTranscriptStates).values(initialGameTranscriptStateValues(gameId));
  const ownerEpoch = await insertOwner(db, gameId, { expiresAt: "2099-01-01T00:00:00.000Z" });
  const agents = () => ["Atlas", "Echo", "Nova"].map((name, i) => new ApiTestMockAgent(`rt06-seat-${i}`, name));
  const config = { ...DEFAULT_CONFIG, maxDiaryFollowUps: 0, diaryRoomAfterPhases: [], formatManifest: ["save_or_eliminate" as const], mingleSessionsPerRound: 1 };
  const store = createDurableGameRunnerStore(db, { gameId, ownerEpoch });
  await expect(new GameRunner(agents(), config, undefined, { gameId, durableTurnStore: { ...store, async commitTurn(draft, input) {
    if (input) throw new Error("Interrupted at outcome before initialization");
    return store.commitTurn(draft);
  } } }).run()).rejects.toThrow("Interrupted at outcome");
  const before = await store.load(gameId), outcome = replayCanonicalEvents(before!.canonicalEvents).retrospectiveOutcomeSource!;
  await expect(settleDurableTerminalGame(db, { gameId, ownerEpoch })).rejects.toMatchObject({ code: "execution_not_terminal" });
  expect(await db.select().from(schema.gameCompletionSettlements)).toHaveLength(0);
  expect(await db.select().from(schema.gameResults)).toHaveLength(0);
  expect(await db.select().from(schema.houseCutJobs)).toHaveLength(0);
  await new GameRunner(agents(), config, undefined, { gameId, durableTurnStore: store }).run();
  const terminal = await store.load(gameId);
  expect(replayCanonicalEvents(terminal!.canonicalEvents).retrospectiveOutcomeSource).toEqual(outcome);
  expect(terminal!.execution.heads.eventSequence).toBeGreaterThan(outcome.eventSequence);
  const completion = (await db.select().from(schema.gamePublications)).find(row => row.kind === "completion")!;
  expect(completion.availableAt).toBeNull();
  await db.update(schema.gameRunOwners).set({ expiresAt: new Date(Date.now() - 1000).toISOString() }).where(eq(schema.gameRunOwners.gameId, gameId));
  let adoptedOwnerEpoch: string | null = null;
  const adopted = await adoptInProgressDurableGamesOnStartup(db, { isAlreadyRunning: () => false, start(input) {
    expect(input.executionState?.status).toBe("terminal"); adoptedOwnerEpoch = input.ownerEpoch;
  } });
  expect(adopted.adopted).toEqual([gameId]);
  const finalOwner = adoptedOwnerEpoch!;
  const settled = await settleDurableTerminalGame(db, { gameId, ownerEpoch: finalOwner });
  expect(settled.settlement.outcome).toBe("completed");
  const sealed = (await db.select().from(schema.gameCompletionSettlements))[0]!;
  expect(sealed.finalEventSequence).toBe(terminal!.execution.heads.eventSequence);
  expect(sealed.finalEventHash).toBe(terminal!.execution.heads.eventHash!);
  expect((await db.select().from(schema.games))[0]!.status).toBe("completed");
  expect((await db.select().from(schema.gameResults))).toHaveLength(1);
  expect((await db.select().from(schema.gamePublications)).find(row => row.kind === "completion")!.availableAt).not.toBeNull();
  expect((await db.select().from(schema.transcripts)).filter(row => row.phase === "RETROSPECTIVE")).toHaveLength(3);
  const again = await settleCapturedGameCompletion(db, gameId, { source: "runner", adoptedOwnerEpoch: finalOwner });
  expect(again.outcome).toBe("already_completed");
  expect(await db.select().from(schema.gameResults)).toHaveLength(1);
  expect(await db.select().from(schema.houseCutJobs)).toHaveLength(1);
  expect(await db.select().from(schema.gamePostgameMedia)).toHaveLength(1);
  expect((await db.select().from(schema.gameRunOwners)).filter(owner => owner.status === "closed")).toHaveLength(1);
}, 30_000);
