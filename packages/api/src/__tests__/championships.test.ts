import { championshipFixture as fixture, policies } from "./championship-fixtures.js";
import { beforeAll, describe, expect, test } from "bun:test";
import { randomUUID } from "node:crypto";
import { eq } from "drizzle-orm";
import { Hono } from "hono";
import { schema } from "../db/index.js";
import { readJson } from "../services/payload-storage.js";
import { testPayloadStore } from "./payload-test-store.js";
import { configureChampionshipDraft, lockChampionshipRoster, publishChampionship, readChampionship, readFrozenCompetitionBuild } from "../services/championships.js";
import { grantAward, publicAgentAwards, revokeAward, createAwardDefinition, publicAwardDefinitions } from "../services/awards.js";
import { createChampionshipRoutes } from "../routes/championships.js";
import { createSessionToken } from "../middleware/auth.js";
import { grantTestAuthority } from "./rbac-fixtures.js";

beforeAll(() => { process.env.JWT_SECRET = "championship-test-secret"; });
describe("championship foundations", () => {
  test("unanswered policy and active seasons cannot lock; no game is created", async () => {
    const { db, event, actorId, seasonId } = await fixture();
    await expect(lockChampionshipRoster(db, event.id, actorId, randomUUID())).rejects.toThrow("Decisions still needed");
    await configureChampionshipDraft(db, event.id, { policies, startDate: "2026-12-25" });
    await db.update(schema.seasons).set({ status: "active" }).where(eq(schema.seasons.id, seasonId));
    await expect(lockChampionshipRoster(db, event.id, actorId, randomUUID())).rejects.toThrow("Finalize");
    expect(await db.select().from(schema.championshipEntries)).toHaveLength(0);
    expect(await db.select().from(schema.games)).toHaveLength(1);
  });
  test("concurrent lock retries preserve one immutable field and 17 UTC match records", async () => {
    const { db, event, actorId, agents } = await fixture();
    await configureChampionshipDraft(db, event.id, { policies, startDate: "2026-12-25" });
    const requestId = randomUUID();
    const locked = await Promise.all([lockChampionshipRoster(db, event.id, actorId, requestId), lockChampionshipRoster(db, event.id, actorId, requestId)]);
    expect(locked[0]!.roleSchedule).toEqual(locked[1]!.roleSchedule);
    expect(await db.select().from(schema.championshipEntries)).toHaveLength(8);
    expect(await db.select().from(schema.championshipMatches)).toHaveLength(17);
    const build = await readFrozenCompetitionBuild(db, event.id, agents[0]!);
    await db.update(schema.agentProfiles).set({ name: "Changed live agent", personality: "Changed", werewolfStrategyStyle: "Changed" }).where(eq(schema.agentProfiles.id, agents[0]!));
    expect(await readFrozenCompetitionBuild(db, event.id, agents[0]!)).toEqual(build);
    expect(build.character.strategyStyle).toBe("Influence strategy");
    expect(build.character.werewolfStrategyStyle).toBe("Werewolf strategy");
    expect(await readChampionship(db, event.slug)).toBeNull();
    await publishChampionship(db, event.id, true);
    const view = await readChampionship(db, event.slug);
    expect(view!.entries).toHaveLength(8);
    expect(view!.matches[16]).toMatchObject({ ordinal: 17, gameKind: "influence", scheduledAt: "2027-01-10T00:00:00.000Z", gameSlug: null });
    const seed = (await readJson(locked[0]!.roleSchedule!)).seed;
    expect(JSON.stringify(view)).not.toContain(seed);
    expect(JSON.stringify(view)).not.toContain(actorId);
    expect(JSON.stringify(view)).not.toContain("Frozen personality");
    expect(view!.lineups.every(row => Object.keys(row).sort().join(",") === "id,roles")).toBe(true);
    expect(await db.select().from(schema.games)).toHaveLength(1);
    const [entry] = await db.select().from(schema.championshipEntries).where(eq(schema.championshipEntries.agentId, agents[0]!));
    testPayloadStore.objects.set(entry!.build.key, new Uint8Array([0]));
    await expect(readFrozenCompetitionBuild(db, event.id, agents[0]!)).rejects.toThrow("integrity mismatch");
  });
  test("awards are idempotent, evidence-bound and revocable without deleting history", async () => {
    const { db, actorId, agents, seasonId } = await fixture();
    const input = { actorId, definitionCode: "season-0-top-eight", recipient: { type: "agent" as const, id: agents[0]! }, sourceSeasonId: seasonId,
      sourceKey: `season:${seasonId}:top-eight`, reason: "Qualified in final standings", evidence: { rank: 1, seasonPoints: 100 }, requestId: randomUUID() };
    const [a, b] = await Promise.all([grantAward(db, input), grantAward(db, input)]);
    expect(a.id).toBe(b.id);
    expect(await db.select().from(schema.awardGrants)).toHaveLength(1);
    await expect(grantAward(db, { ...input, evidence: { rank: 2 } })).rejects.toThrow("different evidence");
    await expect(grantAward(db, { ...input, recipient: { type: "account", id: actorId } })).rejects.toThrow("recipient");
    expect(await publicAgentAwards(db, agents[0]!)).toHaveLength(1);
    await revokeAward(db, { grantId: a.id, actorId, reason: "Corrected qualification", requestId: randomUUID() });
    expect(await publicAgentAwards(db, agents[0]!)).toHaveLength(0);
    expect(await db.select().from(schema.awardGrants)).toHaveLength(1);
    expect(await db.select().from(schema.competitionAudit)).toHaveLength(2);
    expect((await grantAward(db, input)).revoked).toBe(true);
  });
  test("custom definitions are reusable and publicly discoverable", async () => {
    const { db, actorId } = await fixture();
    const definition = { code: "community-helper", title: "Community helper", recipientType: "account" as const, theme: "house" };
    await createAwardDefinition(db, definition);
    await createAwardDefinition(db, definition);
    expect((await publicAwardDefinitions(db)).find(item => item.code === definition.code)).toMatchObject({ recipient: "account", theme: "house" });
    await expect(createAwardDefinition(db, { ...definition, title: "Changed" })).rejects.toThrow("different definition");
    const grant = await grantAward(db, { actorId, definitionCode: definition.code, recipient: { type: "account", id: actorId }, sourceKey: "manual:helper", evidence: { contribution: "fixture" }, reason: "Fixture contribution", requestId: randomUUID() });
    expect(grant.created).toBe(true);
  });
  test("producer routes require explicit authority; public drafts do not leak", async () => {
    const { db, actorId, event } = await fixture();
    const app = new Hono().route("/", createChampionshipRoutes(db));
    expect((await app.request(`/api/championships/${event.slug}`)).status).toBe(404);
    expect((await app.request(`/api/admin/championships/${event.id}`)).status).toBe(401);
    const token = await createSessionToken(actorId);
    const headers = { Authorization: `Bearer ${token}` };
    expect((await app.request(`/api/admin/championships/${event.id}`, { headers })).status).toBe(403);
    await grantTestAuthority(db, actorId, ["manage_championships"]);
    expect((await app.request(`/api/admin/championships/${event.id}`, { headers })).status).toBe(200);
    expect((await app.request("/api/admin/awards", { method: "POST", headers, body: "{}" })).status).toBe(403);
  });
});
